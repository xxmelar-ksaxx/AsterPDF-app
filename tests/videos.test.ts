import test from 'node:test';
import assert from 'node:assert/strict';
import { PDFDocument, PDFName, PDFDict, PDFArray, PDFRawStream } from 'pdf-lib';
import { attachOverlayPackage, embedOverlays, readOverlayPackage, type OverlayObject } from '../src/pdf/overlays';
import { storeVideo, clearVideos, videoBlob } from '../src/pdf/video-assets';
import { prepareCommentData } from '../src/pdf/comment-save-data';
import type { PageViewport } from 'pdfjs-dist';

const poster='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=';
const viewport={width:600,height:400,convertToPdfPoint:(x:number,y:number)=>[x,400-y]} as PageViewport;
const pages=[{pageId:'source-0',index:0,viewport}];
test('video assets are embedded once, survive reopen/autosave, and stay out of the editable base',async()=>{
 const pdf=await PDFDocument.create();pdf.addPage([600,400]);const base=await pdf.save();
 const payload=new Uint8Array(100000).map((_,i)=>i%251);
 storeVideo('asset-1',new Blob([payload],{type:'video/mp4'}));
 const object:OverlayObject={id:'video-1',videoId:'asset-1',name:'Demo.mp4',kind:'video',pageId:'source-0',x:.1,y:.2,width:.4,height:.3,color:'#000000',lineWidth:1,image:poster};
 const objects=[object,{...object,id:'video-2',x:.5}];
 let bytes=await attachOverlayPackage(await embedOverlays(base,objects,pages),base,objects);
 const firstSize=bytes.length;
 const verify=async()=>{
  const doc=await PDFDocument.load(bytes);
  const streams=doc.context.enumerateIndirectObjects().filter(([,o])=>o instanceof PDFRawStream&&o.dict.get(PDFName.of('Type'))===PDFName.of('EmbeddedFile'));
  assert.equal(streams.length,1);
  assert.equal(doc.getPage(0).node.Annots()!.size(),2);
  const annotation=doc.context.lookup(doc.getPage(0).node.Annots()!.get(0),PDFDict);
  assert.equal(annotation.get(PDFName.of('Subtype')),PDFName.of('RichMedia'));
  assert.ok(annotation.lookup(PDFName.of('AP'),PDFDict).has(PDFName.of('N')),'Video has a thumbnail appearance');
  assert.ok(annotation.lookup(PDFName.of('RichMediaContent'),PDFDict).lookup(PDFName.of('Configurations'),PDFArray).size());
  clearVideos();const restored=await readOverlayPackage(bytes);assert.ok(restored);
  assert.deepEqual(restored.objects,objects);
  assert.deepEqual(new Uint8Array(await videoBlob('asset-1')!.arrayBuffer()),payload);
  const editable=await PDFDocument.load(restored.base);
  assert.equal(editable.catalog.has(PDFName.of('AsterPDFVideoAssetsV1')),false);
  assert.ok(!editable.context.enumerateIndirectObjects().some(([,o])=>o instanceof PDFRawStream&&o.dict.get(PDFName.of('Type'))===PDFName.of('EmbeddedFile')));
  return restored;
 };
 const restored=await verify();
 bytes=await attachOverlayPackage(await embedOverlays(restored.base,objects,pages),restored.base,objects);await verify();
 assert.ok(bytes.length<firstSize+2000);
 const result=await prepareCommentData(bytes,[{id:'note',page:1,x:20,y:20,author:'Test',text:'Review',date:'2026-10-28'}]);
 bytes=result.bytes;
 const reopened=await readOverlayPackage(bytes);assert.ok(reopened);assert.deepEqual(reopened.objects,objects);
 assert.deepEqual(new Uint8Array(await videoBlob('asset-1')!.arrayBuffer()),payload);
 const visible=await PDFDocument.load(bytes);assert.equal(visible.getPage(0).node.Annots()!.size(),3);
 const clean=await PDFDocument.load(reopened.base);assert.equal(clean.getPage(0).node.Annots()!.size(),1);
 assert.ok(bytes.length<firstSize+5000);
 const hidden=[{...object,hidden:true}];
 const hiddenBytes=await attachOverlayPackage(await embedOverlays(reopened.base,hidden,pages),reopened.base,hidden);
 clearVideos();assert.ok(await readOverlayPackage(hiddenBytes));assert.ok(videoBlob('asset-1'),'Hidden videos retain their assets');
 const removed=await PDFDocument.load(await embedOverlays(reopened.base,[],pages));
 assert.ok(!removed.catalog.has(PDFName.of('AsterPDFVideoAssetsV1')),'Deleting the last video removes its embedded asset');
 clearVideos();
});
