const { _electron } = require('playwright');
const { PDFDocument, PDFName, decodePDFRawStream } = require('pdf-lib');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');

async function main() {
  const project = path.join(__dirname, '..');
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'asterpdf-draw-workspace-'));
  const sourcePath = path.join(temporary, 'drawing.pdf'), savedPath = path.join(temporary, 'saved.pdf');
  const pdf = await PDFDocument.create(); pdf.addPage([500, 600]);
  await fs.writeFile(sourcePath, await pdf.save());
  const electron = await _electron.launch({ executablePath: require('electron'), args: [project, `--user-data-dir=${temporary}`], timeout: 60000 });
  try {
    const window = await electron.firstWindow(); window.setDefaultTimeout(12000);
    await electron.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setBounds({ width: 1380, height: 1000 }));
    await window.getByText('Every detail, in view.').waitFor();
    await electron.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, sourcePath);
    await window.getByRole('button', { name: 'Open a file', exact: true }).first().click();
    await window.locator('.page-stage canvas').first().waitFor();
    await window.getByRole('button', { name: 'Draw', exact: true }).click();
    const inspector = window.getByLabel('Drawing properties and layers');
    await inspector.waitFor();
    const stage = window.locator('.page-stage').first();
    const objects = stage.locator('.overlay-object');
    const drag = async (from, to, shift = false) => {
      const box = await stage.boundingBox();
      if (shift) await window.keyboard.down('Shift');
      await window.mouse.move(box.x + from[0] * box.width, box.y + from[1] * box.height);
      await window.mouse.down();
      await window.mouse.move(box.x + to[0] * box.width, box.y + to[1] * box.height, { steps: 8 });
      await window.mouse.up();
      if (shift) await window.keyboard.up('Shift');
    };
    const number = async (name, value) => { const input = inspector.getByRole('spinbutton', { name, exact: true }); await input.fill(String(value)); await input.press('Tab'); };
    await window.getByRole('button', { name: 'Draw rectangle', exact: true }).click();
    await drag([.15, .13], [.48, .32]);
    assert.equal(await objects.count(), 1);
    assert.equal(await window.getByRole('button', { name: 'Select objects' }).getAttribute('aria-pressed'), 'true');
    assert.equal(await stage.locator('[data-resize-handle]').count(), 8);
    const firstId = await objects.first().getAttribute('data-overlay-id');
    const shape = stage.locator(`[data-overlay-id="${firstId}"]`);
    const name = inspector.getByRole('textbox', { name: 'Layer name' });
    await name.fill('Card'); await name.press('Enter');
    await number('Corner radius', 18); await number('Opacity', 60);
    await inspector.getByRole('button', { name: 'Fill color', exact: true }).click();
    const hex = window.getByRole('textbox', { name: 'Hex color', exact: true });
    await hex.fill('#b0d4ef'); await hex.press('Enter'); await hex.press('Escape');
    assert.equal(await shape.locator('path').getAttribute('fill'), '#b0d4ef');
    assert.equal(await shape.locator('g[opacity]').first().getAttribute('opacity'), '0.6');
    // Resizing uses the same corner interaction as placed images.
    const handle = shape.locator('[data-resize-handle="nw"]');
    const h = await handle.boundingBox();
    const oldWidth = Number(await inspector.getByRole('spinbutton', { name: 'Width', exact: true }).inputValue());
    await window.mouse.move(h.x + h.width / 2, h.y + h.height / 2); await window.mouse.down();
    await window.mouse.move(h.x - 25, h.y - 15, { steps: 5 }); await window.mouse.up();
    assert.ok(Number(await inspector.getByRole('spinbutton', { name: 'Width', exact: true }).inputValue()) > oldWidth);
    // Closing the panel preserves selection; reopening shows its properties.
    await inspector.getByRole('button', { name: 'Hide drawing panel' }).click();
    assert.equal(await inspector.count(), 0);
    await window.getByRole('button', { name: 'Toggle drawing panel' }).click();
    assert.equal(await inspector.getByRole('textbox', { name: 'Layer name' }).inputValue(), 'Card');
    await window.getByRole('button', { name: 'Hide layer Card', exact: true }).click();
    assert.equal(await shape.count(), 0);
    await window.getByRole('button', { name: 'Show layer Card', exact: true }).click();
    await window.getByRole('button', { name: 'Lock layer Card', exact: true }).click();
    assert.equal(await shape.locator('[data-resize-handle]').count(), 0);
    assert.equal(await inspector.getByRole('spinbutton', { name: 'Corner radius' }).isDisabled(), true);
    await window.getByRole('button', { name: 'Unlock layer Card', exact: true }).click();
    // Drawing over an existing shape must create a new object instead of dragging it.
    await window.getByRole('button', { name: 'Draw ellipse', exact: true }).click();
    await drag([.2, .2], [.38, .34], true);
    assert.equal(await objects.count(), 2);
    const w = Number(await inspector.getByRole('spinbutton', { name: 'Width', exact: true }).inputValue());
    const height = Number(await inspector.getByRole('spinbutton', { name: 'Height', exact: true }).inputValue());
    assert.ok(Math.abs(w - height) < .2);
    const shortcut = process.platform === 'darwin' ? 'Meta' : 'Control';
    await window.keyboard.press(`${shortcut}+d`);
    assert.equal(await objects.count(), 3);
    await window.keyboard.press('Delete'); assert.equal(await objects.count(), 2);
    await window.getByRole('button', { name: 'Undo drawing' }).click(); assert.equal(await objects.count(), 3);
    await window.getByRole('button', { name: 'Redo drawing' }).click(); assert.equal(await objects.count(), 2);
    await window.getByRole('button', { name: 'Select layer Card', exact: true }).click();
    await window.getByRole('button', { name: 'Bring forward', exact: true }).click();
    assert.equal(await objects.last().getAttribute('data-overlay-id'), firstId);
    const oldX = Number(await inspector.getByRole('spinbutton', { name: 'X', exact: true }).inputValue());
    await window.keyboard.press('Shift+ArrowRight');
    const newX = Number(await inspector.getByRole('spinbutton', { name: 'X', exact: true }).inputValue());
    assert.ok(Math.abs(newX - oldX - 10) < .2);
    await window.locator(`[data-layer-id="${firstId}"]`).dragTo(window.locator('.draw-layer').last());
    assert.equal(await objects.first().getAttribute('data-overlay-id'), firstId);
    assert.equal(await window.locator('.draw-layer').last().getAttribute('data-layer-id'), firstId);
    await window.locator(`[data-layer-id="${firstId}"]`).dragTo(window.locator('.draw-layer').first());
    assert.equal(await objects.last().getAttribute('data-overlay-id'), firstId);
    assert.equal(await window.getByText('Drop a PDF, DOCX, or image file to open it.', { exact: true }).count(), 0);
    // Click-placement makes a default shape; Escape cancels an in-progress drag.
    await window.keyboard.press('r');
    const box = await stage.boundingBox();
    await stage.click({ position: { x: box.width * .6, y: box.height * .2 } });
    assert.equal(await objects.count(), 3);
    await window.keyboard.press('r');
    await window.mouse.move(box.x + box.width * .5, box.y + box.height * .4); await window.mouse.down();
    await window.mouse.move(box.x + box.width * .7, box.y + box.height * .5); await window.keyboard.press('Escape'); await window.mouse.up();
    assert.equal(await objects.count(), 3);
    await window.getByRole('button', { name: 'Select layer Card', exact: true }).click();
    await window.getByRole('button', { name: 'Lock layer Card', exact: true }).click();
    await window.getByRole('button', { name: 'Hide layer Ellipse', exact: true }).click();
    if (process.env.ASTERPDF_DRAW_PREVIEW) await window.screenshot({ path: process.env.ASTERPDF_DRAW_PREVIEW });
    await electron.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, savedPath);
    await electron.evaluate(({ Menu }) => Menu.getApplicationMenu().items.find(item => item.label === 'File').submenu.items.find(item => item.label === 'Save As…').click());
    await window.locator('.document-title strong').filter({ hasText: path.basename(savedPath) }).waitFor({ timeout: 30000 });
    await window.locator('.saving-spinner').waitFor({ state: 'hidden', timeout: 30000 });
    const saved = await PDFDocument.load(await fs.readFile(savedPath));
    const stream = saved.context.lookup(saved.catalog.get(PDFName.of('AsterPDFEditableObjectsV1')));
    const restored = JSON.parse(new TextDecoder().decode(decodePDFRawStream(stream).decode()));
    const card = restored.find(object => object.name === 'Card');
    assert.equal(card.fill, '#b0d4ef'); assert.equal(card.radius, 18); assert.equal(card.opacity, .6); assert.equal(card.locked, true);
    assert.equal(restored.find(object => object.kind === 'ellipse').hidden, true);
    await electron.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, savedPath);
    await window.getByRole('button', { name: 'Open file', exact: true }).click();
    await window.getByRole('button', { name: 'Draw', exact: true }).click();
    await window.getByRole('button', { name: 'Unlock layer Card', exact: true }).waitFor();
    await window.getByRole('button', { name: 'Show layer Ellipse', exact: true }).waitFor();
    console.log('Draw workspace: placement, styling, resize, panel, layers, constraints, shortcuts, cancellation, and save/reopen passed.');
  } finally {
    await electron.firstWindow().then(window => window.evaluate(() => window.aster.setDirty(false))).catch(() => {});
    await electron.close().catch(() => {});
    await fs.rm(temporary, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
